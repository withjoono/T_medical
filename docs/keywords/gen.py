# 2) 대학별
for name, zone, itype, forms, risky in U:
    for f in forms:
        risk = risky.get(f, "")
        for med in MED_CORE:
            for t in T1:
                add(f + med + t, name, zone, itype, name, "T1 핵심", risk)
            for t in TYPE_TERMS[itype]:
                add(f + med + t, name, zone, itype, name, "T2 유형", risk)
        for med in MED_LONG:
            for t in T3:
                add(f + med + t, name, zone, itype, name, "T3 행동·정보", risk)

