rows, seen = [], set()
def add(kw, field, univ, group, tier, risk=""):
    if kw in seen: return
    seen.add(kw)
    rows.append([kw, field, univ, group, tier, risk])

for field, (meds, univs) in A.items():
    # 계열 공통
    for med in meds:
        for t in COMMON_BY_FIELD:
            add(med + t, field, "(공통)", field + " 공통", "T0")
    for name, forms, risky in univs:
        for f in forms:
            risk = risky.get(f, "")
            for med in meds:
                for t in T1:
                    add(f + med + t, field, name, f"{field} · {name}", "T1 핵심", risk)
            for t in T3:
                add(f + meds[0] + t, field, name, f"{field} · {name}", "T3 행동·정보", risk)

