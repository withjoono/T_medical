export type InterviewTypeKey = "mmi" | "injeokseong" | "jesimun";

export type TypeTable = {
  /** "top" = 히어로 바로 아래(요약), "univ" = 대학 표 아래(기본) */
  slot?: "top" | "univ";
  eyebrow: string;
  title: string;
  subtitle?: string;
  head: string[];
  rows: string[][];
  caption?: string;
  tone?: "default" | "muted";
};

export type InterviewType = {
  key: InterviewTypeKey;
  href: string;
  /** 페이지 제목에 쓰는 정식 명칭 */
  name: string;
  /** 표·배지에 쓰는 짧은 이름 */
  short: string;
  /** 한 줄 정의 — 허브 카드와 히어로 배지 */
  tagline: string;
  /** 히어로 본문 */
  lede: string;
  /** 이 방식이 무엇인가 — 요강에서 확인되는 공통 특징 */
  what: string[];
  /** 준비 포인트 */
  drills: { title: string; body: string }[];
  /** 흔한 실수 */
  pitfalls: string[];
  /** 요강에서 뽑은 표 — slot 에 따라 히어로 아래 또는 대학 표 아래에 들어간다 */
  tables?: TypeTable[];
  /** 왜 1:1 온라인인가 — 유형마다 이기는 지점이 다르다 */
  edges?: {
    title: string;
    subtitle?: string;
    items: { title: string; body: string }[];
    /** 약점과 보완 설계 — 두는 유형만 둔다 */
    weakness?: { title: string; subtitle?: string; head: string[]; rows: string[][]; caption?: string };
  };
  /** 1차 불합격 누수 대기 예약 — 대학별 특강을 여는 유형(MMI)만 */
  waitlist?: { title: string; subtitle: string; boxTitle: string; items: string[] };
  metaTitle: string;
  metaDescription: string;
};

