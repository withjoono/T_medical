/* -------------------------------------------------------------------------
 * 대학으로 유형 찾기 — /interview 의 첫 진입점.
 *
 *   방문자는 자기 면접이 MMI 인지 모른다. 아는 것은 지원 대학 이름이다.
 *   그래서 허브의 1차 진입은 유형이 아니라 대학이어야 한다.
 * ---------------------------------------------------------------------- */

export type FinderUniv = {
  slug: string;
  short: string;
  /** 이 대학의 주된 면접 유형. 면접을 보지 않으면 null */
  type: InterviewType | null;
  /** 수업 일정·예약 블록이 있는 대학인가 */
  hasClassPage: boolean;
};

export function finderByZone(): { zone: string; univs: FinderUniv[] }[] {
  const out = new Map<string, FinderUniv[]>();
  for (const u of UNIV_PAGES) {
    const assign = ASSIGN[u.slug];
    const noIv =
      u.hasInterview === false ||
      (NO_INTERVIEW_SLUGS as readonly string[]).includes(u.slug);
    if (!assign && !noIv) continue; // 아직 분류되지 않은 대학은 내보내지 않는다
    const row: FinderUniv = {
      slug: u.slug,
      short: u.short,
      type: assign ? getInterviewType(assign.primary) ?? null : null,
      hasClassPage: u.hasClassPage,
    };
    const list = out.get(u.zone);
    if (list) list.push(row);
    else out.set(u.zone, [row]);
  }
  return [...out.entries()].map(([zone, univs]) => ({ zone, univs }));
}
