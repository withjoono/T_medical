export function rubricText(m: UnivMock): string {
  const used = [m.rubric, ...[RUBRIC_PASSAGE, RUBRIC_DOC].filter((r) => r.id !== m.rubric.id && m.items.some((it) => rubricOf(m, it).id === r.id))];
  const nameOf = (it: MockItem, k: string) => rubricOf(m, it).factors.find((x) => x.key === k)?.name ?? k;
  return [
    "[채점 방법] 문항(방)마다 그 문항의 채점 틀에 있는 역량을 1~5점으로 매긴다. 점수(100점) = Σ 비중 × (점수 ÷ 5) − 감점. 총점 = 문항(방) 점수의 평균.",
    ...used.flatMap((r) => [
      `[역량별 수준 — ${r.label}]`,
      ...r.factors.map((c) => `· ${c.name}(${c.weight}%) — 5점: ${c.levels[5]} / 3점: ${c.levels[3]} / 1점: ${c.levels[1]}`),
    ]),
    `[감점] 해당할 때마다 −${RED_FLAG_PENALTY}점, 최대 −${RED_FLAG_CAP}점: ${RED_FLAGS.map((r) => r.label).join(" · ")}`,
    "[주의] 받아쓰기에서 근거를 찾을 수 없는 역량은 추측으로 올리지 않는다. 말투·유창함은 점수에 넣지 않는다.",
    ...m.items.flatMap((it) => [
      `[${it.title} — ${rubricOf(m, it).label}] 5점 답변에 들어 있는 것`,
      ...it.keyPoints.map((k) => `· (${nameOf(it, k.c)}) ${k.text}`),
      `· 흔한 감점 답변: ${it.pitfalls.join(" / ")}`,
    ]),
  ].join("\n");
}

export function toItem(m: UnivMock, it: MockItem): SetItem {
  const nameOf = (k: string) => rubricOf(m, it).factors.find((x) => x.key === k)?.name ?? k;
  return {
    id: it.id,
    question: it.first,
    ...(it.passage ? { passages: [{ label: "제시문", text: it.passage }] } : {}),
    subQuestions: it.main.map((text, i) => ({ label: String(i + 1), text })),
    followups: it.followups,
    meta: { kind: it.kind, topic: it.title, subject: `채점 틀: ${rubricOf(m, it).label}`, scope: "T메디 제작(기출 아님)" },
    review: { focus: it.focus, keyPoints: it.keyPoints.map((k) => k.text), pitfall: it.pitfalls.join(" / ") },
    hint: { intent: it.focus },
    memo: {
      issues: it.keyPoints.map((k) => `${nameOf(k.c)}: ${k.text}`),
      pitfalls: it.pitfalls,
      followDirections: [
        "주질문을 순서대로 묻고, 남은 시간에 꼬리질문을 고른다. 학생이 이미 답한 것은 다시 묻지 않는다.",
        "서류형 문항에서는 학생이 고른 활동의 세부(직접 한 일, 방법, 한계)를 파고든다.",
        ...it.followups,
      ],
    },
  };
}

