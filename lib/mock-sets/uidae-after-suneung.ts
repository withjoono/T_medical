export type ScoreMap = Record<string, 1 | 2 | 3 | 4 | 5>;

/** 방 점수(0~100) = Σ 비중 × (역량 점수 ÷ 5) − 감점. 감점 규칙은 서울대 모의면접과 같다 */
export function scoreWith(rubric: Rubric, s: ScoreMap, redFlags: number = 0): number {
  const raw = rubric.factors.reduce((n, f) => n + f.weight * ((s[f.key] ?? 1) / 5), 0);
  const penalty = Math.min(RED_FLAG_CAP, Math.max(0, redFlags) * RED_FLAG_PENALTY);
  return Math.max(0, Math.round((raw - penalty) * 10) / 10);
}

