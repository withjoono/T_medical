function rubricText(stations: readonly MockStation[]): string {
  const head = [
    "[채점 방법] 방마다 여섯 역량을 1~5점으로 매긴다. 방 점수(100점) = Σ 비중 × (점수 ÷ 5) − 감점. 총점 = 네 방의 평균.",
    "[역량별 수준]",
    ...COMPETENCIES.map((c) => `· ${c.name}(${c.weight}%) — 5점: ${c.levels[5]} / 3점: ${c.levels[3]} / 1점: ${c.levels[1]}`),
    `[감점] 해당할 때마다 −${RED_FLAG_PENALTY}점, 방마다 최대 −${RED_FLAG_CAP}점: ${RED_FLAGS.map((r) => r.label).join(" · ")}`,
    "[주의] 받아쓰기에서 근거를 찾을 수 없는 역량은 추측으로 올리지 않는다. 말투·유창함은 점수에 넣지 않는다.",
  ];
  const body = stations.flatMap((s) => [
    `[${s.title}] 5점 답변에 들어 있는 것`,
    ...s.keyPoints.map((k) => `· (${COMPETENCIES.find((c) => c.key === k.c)!.name}) ${k.text}`),
    `· 흔한 감점 답변: ${s.pitfalls.join(" / ")}`,
  ]);
  return [...head, ...body].join("\n");
}

