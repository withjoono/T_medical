export type RoomScore = Record<CompetencyKey, 1 | 2 | 3 | 4 | 5>;

/** 방 점수(0~100) = Σ 비중 × (역량 점수 ÷ 5) − 감점 */
export function roomScore(s: RoomScore, redFlags: number = 0): number {
  const raw = COMPETENCIES.reduce((n, c) => n + c.weight * (s[c.key] / 5), 0);
  const penalty = Math.min(RED_FLAG_CAP, Math.max(0, redFlags) * RED_FLAG_PENALTY);
  return Math.max(0, Math.round((raw - penalty) * 10) / 10);
}

/** 총점 = 방 점수의 평균(소수 첫째 자리) */
export function totalScore(rooms: number[]): number {
  if (!rooms.length) return 0;
  return Math.round((rooms.reduce((a, b) => a + b, 0) / rooms.length) * 10) / 10;
}

export const bandOf = (total: number) => BANDS.find((b) => total >= b.min) ?? BANDS[BANDS.length - 1];

/** 누적 총점 목록(본인 제외, 사람당 첫 응시)으로 등수를 낸다. 표본이 모자라면 rank 는 null */
export function rankOf(total: number, others: number[]): { rank: number | null; of: number; topPercent: number | null } {
  const of = others.length + 1;
  if (of < RANKING.minSample) return { rank: null, of, topPercent: null };
  const rank = 1 + others.filter((x) => x > total).length;
  return { rank, of, topPercent: Math.max(1, Math.round((rank / of) * 100)) };
}

